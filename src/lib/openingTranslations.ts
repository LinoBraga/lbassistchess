export function translateOpeningName(name: string): string {
  const exact = OPENING_TRANSLATIONS[name.trim()];
  if (exact) return exact;

  return SUFFIX_TRANSLATIONS.reduce(
    (translated, [pattern, replacement]) =>
      translated.replace(pattern, replacement),
    name,
  );
}
